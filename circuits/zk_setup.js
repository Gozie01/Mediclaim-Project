// ─────────────────────────────────────────────────────────────────────────────
// zk_setup.js — Phase 3: Full ZK circuit setup pipeline
//
// Prerequisites (run once):
//   cargo install circom
//   circom circuits/consent_proof.circom --r1cs --wasm --sym \
//          -o circuits/build -l node_modules/circomlib/circuits
//
// Then run this script:
//   node circuits/zk_setup.js
//
// Outputs:
//   circuits/build/consent_proof_final.zkey   → proving key
//   circuits/build/verification_key.json       → verification key
//   contracts/ZKConsentVerifier_real.sol        → real Groth16 verifier
//   circuits/build/sample_proof.json            → example proof for testing
// ─────────────────────────────────────────────────────────────────────────────

const snarkjs  = require("snarkjs");
const { buildPoseidon } = require("circomlibjs");
const fs   = require("fs");
const path = require("path");
const { ethers } = require("ethers");

const BUILD_DIR = path.join(__dirname, "build");
const R1CS      = path.join(BUILD_DIR, "consent_proof.r1cs");
const WASM      = path.join(BUILD_DIR, "consent_proof_js/consent_proof.wasm");
const ZKEY_0    = path.join(BUILD_DIR, "consent_proof_0.zkey");
const ZKEY_FINAL= path.join(BUILD_DIR, "consent_proof_final.zkey");
const VK_PATH   = path.join(BUILD_DIR, "verification_key.json");
const PROOF_OUT = path.join(BUILD_DIR, "sample_proof.json");

async function setup() {
  console.log("\n╔══════════════════════════════════════════════════════╗");
  console.log("║       MediClaim ZK Setup — Groth16 (Gap 3)           ║");
  console.log("╚══════════════════════════════════════════════════════╝\n");

  if (!fs.existsSync(BUILD_DIR)) fs.mkdirSync(BUILD_DIR, { recursive: true });

  if (!fs.existsSync(R1CS)) {
    console.error("❌  R1CS file not found. Run the circom compiler first:");
    console.error("    circom circuits/consent_proof.circom --r1cs --wasm --sym \\");
    console.error("           -o circuits/build -l node_modules/circomlib/circuits");
    process.exit(1);
  }

  // ── 1. Powers of Tau ceremony (phase 1 trusted setup) ────────────────────
  console.log("1/5  Powers of Tau (phase 1)...");
  await snarkjs.powersOfTau.newAccumulator(snarkjs.bn128, 12, path.join(BUILD_DIR, "pot12_0000.ptau"));
  await snarkjs.powersOfTau.contribute(
    path.join(BUILD_DIR, "pot12_0000.ptau"),
    path.join(BUILD_DIR, "pot12_0001.ptau"),
    "MediClaim First Contributor", "mediclaim-entropy-2026"
  );
  await snarkjs.powersOfTau.preparePhase2(
    path.join(BUILD_DIR, "pot12_0001.ptau"),
    path.join(BUILD_DIR, "pot12_final.ptau")
  );
  console.log("     ✔ Powers of Tau complete");

  // ── 2. Groth16 circuit-specific setup (phase 2) ───────────────────────────
  console.log("2/5  Groth16 phase 2 setup...");
  await snarkjs.groth16.setup(R1CS, path.join(BUILD_DIR, "pot12_final.ptau"), ZKEY_0);
  await snarkjs.zKey.contribute(ZKEY_0, ZKEY_FINAL, "MediClaim Contributor", "mediclaim-zkey-entropy-2026");
  console.log("     ✔ Proving key generated");

  // ── 3. Export verification key ─────────────────────────────────────────────
  console.log("3/5  Exporting verification key...");
  const vKey = await snarkjs.zKey.exportVerificationKey(ZKEY_FINAL);
  fs.writeFileSync(VK_PATH, JSON.stringify(vKey, null, 2));
  console.log(`     ✔ Verification key saved to ${VK_PATH}`);

  // ── 4. Generate sample proof ───────────────────────────────────────────────
  console.log("4/5  Generating sample proof...");
  const poseidon     = await buildPoseidon();
  const patientAddr  = "0xf39Fd6e51aad88F6F4ce6aB8827279cffFb92266"; // demo account
  const patientSecret = BigInt("0x" + Array.from({length:32}, () => Math.floor(Math.random()*256).toString(16).padStart(2,"0")).join(""));
  const addrInt      = BigInt(patientAddr);
  const commitment   = poseidon.F.toString(poseidon([addrInt, patientSecret]));

  const input = {
    patientSecret:     patientSecret.toString(),
    patientAddressInt: addrInt.toString(),
    commitment:        commitment,
  };

  const { proof, publicSignals } = await snarkjs.groth16.fullProve(input, WASM, ZKEY_FINAL);
  fs.writeFileSync(PROOF_OUT, JSON.stringify({ proof, publicSignals, input: { commitment } }, null, 2));
  console.log(`     ✔ Sample proof saved to ${PROOF_OUT}`);

  // ── 5. Export Solidity verifier ────────────────────────────────────────────
  console.log("5/5  Exporting Solidity verifier...");
  const solidityVerifier = await snarkjs.zKey.exportSolidityVerifier(ZKEY_FINAL, {
    groth16Template: "// SPDX-License-Identifier: GPL-3.0\npragma solidity ^0.8.20;\n// Auto-generated by snarkjs\n"
  });

  // Wrap in our IZKConsentVerifier interface
  const wrapped = solidityVerifier
    .replace("contract Verifier {", "contract ZKConsentVerifier_Real {")
    + `
// ─────────────────────────────────────────────────────────────────────────────
// To use: replace ZKConsentVerifier.sol with this file and update deploy.js
// ─────────────────────────────────────────────────────────────────────────────
`;
  fs.writeFileSync(
    path.join(__dirname, "../contracts/ZKConsentVerifier_real.sol"),
    wrapped
  );
  console.log("     ✔ Real Groth16 verifier saved to contracts/ZKConsentVerifier_real.sol");

  console.log("\n╔══════════════════════════════════════════════════════╗");
  console.log("║         ZK Setup Complete ✓  (Gap 3 activated)       ║");
  console.log("╚══════════════════════════════════════════════════════╝");
  console.log("\nNext: deploy ZKConsentVerifier_real.sol and call enableZKEnforcement()");
  console.log("      Then grantConsentWithZKProof() will enforce real Groth16 proofs\n");
}

setup().catch(e => { console.error(e); process.exit(1); });
